/**
 * 创建 Vuetify 的自定义图标集：直接返回 SVG path，
 * 组件中用 icon="mdi-xxx" 即可正常渲染。
 */
export function createMdiSvgSet() {
  return {
    component: (props: { icon: string }) => {
      // 返回 h() 需要的 svg 结构
      const path = mdiIcons[props.icon]
      if (!path) return null
      return {
        tag: 'svg',
        attrs: {
          viewBox: '0 0 24 24',
          role: 'img',
          'aria-hidden': 'true',
        },
        children: [{ tag: 'path', attrs: { d: path } }],
      }
    },
  }
}
